
// ===============================================
// PharmaCore - Purchase Validation
// ===============================================

const { z } = require("zod");

// ===============================================
// Purchase Date Validation
// ===============================================

const purchaseDateSchema = z
  .string()
  .trim()
  .refine((value) => {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
      return false;
    }

    const date = new Date(`${value}T00:00:00`);

    return (
      !Number.isNaN(date.getTime()) &&
      date.toISOString().startsWith(value)
    );
  }, {
    message: "Purchase date must be a valid YYYY-MM-DD date."
  });

// ===============================================
// Purchase Item Validation
// ===============================================

const purchaseItemSchema = z.object({
  medicineId: z.coerce
    .number()
    .int("Medicine ID must be a whole number.")
    .positive("Please select a valid medicine."),

  quantity: z.coerce
    .number()
    .int("Quantity must be a whole number.")
    .positive("Quantity must be greater than zero."),

  unitPrice: z.coerce
    .number()
    .finite("Unit price must be a valid number.")
    .nonnegative("Unit price cannot be negative.")
});

// ===============================================
// Notes Validation
// Accepts omitted or null notes safely.
// ===============================================

const notesSchema = z.preprocess(
  (value) => {
    if (value === null || value === undefined) {
      return "";
    }

    return value;
  },
  z.string()
    .trim()
    .max(1000, "Notes cannot exceed 1000 characters.")
);

// ===============================================
// Create Purchase Validation
// purchaseNumber is generated by the backend.
// ===============================================

const createPurchaseSchema = z.object({
  purchaseDate: purchaseDateSchema,

  supplierId: z.coerce
    .number()
    .int("Supplier ID must be a whole number.")
    .positive("Please select a valid supplier."),

  notes: notesSchema,

  items: z.array(purchaseItemSchema)
    .min(1, "Add at least one medicine to the purchase.")
});

// ===============================================
// Update Purchase Validation
// ===============================================

const updatePurchaseSchema = z.object({
  purchaseDate: purchaseDateSchema.optional(),

  supplierId: z.coerce
    .number()
    .int("Supplier ID must be a whole number.")
    .positive("Please select a valid supplier.")
    .optional(),

  notes: notesSchema.optional(),

  items: z.array(purchaseItemSchema)
    .min(1, "Add at least one medicine to the purchase.")
    .optional()
}).refine(
  (data) => Object.keys(data).length > 0,
  {
    message: "Provide at least one field to update."
  }
);

// ===============================================
// Exports
// ===============================================

module.exports = {
  purchaseDateSchema,
  purchaseItemSchema,
  createPurchaseSchema,
  updatePurchaseSchema
};